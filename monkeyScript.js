// Simple chatbot that returns a random string of letters
const chatbot = {
  name: "Monkey",
  /**
   * Generate a random response consisting of 20 characters.
   */
  reply(question) {
    const letters = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
    let response = "";
    for (let i = 0; i < 20; i++) {
      const index = Math.floor(Math.random() * letters.length);
      response += letters[index];
    }
    return response;
  }
};

// DOM element references
const inputEl = document.getElementById("input");
const outputEl = document.getElementById("output");
const sendBtn = document.querySelector(".send-button");

// Automatically scroll to the bottom of the chatbot
const chatbotContainer = document.getElementById("chatbot-container");

// Add an event listener to the input element to listen for user input
// Send message when Enter is pressed
inputEl.addEventListener("keydown", event => {
  if (event.key === "Enter") {
    sendMessage();
  }
});

// Send message when the send button is clicked
sendBtn.addEventListener("click", sendMessage);

function sendMessage() {
  // Enforce character limit in JS (in addition to HTML)
  const userInput = inputEl.value.trim().slice(0, 140);

  // Don't send empty messages
  if (!userInput) return;

  // Clear the input field
  inputEl.value = "";

  // --- SECURITY FIX: Prevent XSS ---
  // Instead of using innerHTML with user input, now use textContent/createTextNode
  const userPara = document.createElement("p");
  const userLabel = document.createElement("strong");
  userLabel.className = "blue-text";
  userLabel.textContent = "You: ";

  userPara.appendChild(userLabel);
  // This ensures any HTML tags typed by the user are rendered as plain text
  userPara.appendChild(document.createTextNode(userInput));
  outputEl.appendChild(userPara);

  // Create a specific element for the typing indicator
  const typingPara = document.createElement("p");
  typingPara.innerHTML = "<strong>Monkey:</strong> Monkey is typing...";
  outputEl.appendChild(typingPara);

  chatbotContainer.scrollTop = chatbotContainer.scrollHeight;

  // Generate the chatbot's response after a brief pause
  setTimeout(() => {
    // Remove the specific typing indicator element
    if (typingPara.parentNode === outputEl) {
      outputEl.removeChild(typingPara);
    }

    const chatbotResponse = chatbot.reply(userInput);

    // Create the Monkey's response element
    // innerHTML is safe here because 'chatbotResponse' is generated by our code, not the user
    const monkeyPara = document.createElement("p");
    monkeyPara.innerHTML = `<strong>Monkey:</strong> ${chatbotResponse}`;
    outputEl.appendChild(monkeyPara);

    chatbotContainer.scrollTop = chatbotContainer.scrollHeight;
  }, 1000);
}

// Open pop-up form
// Show the chat window and hide the open button
function openForm() {
  document.getElementById("chatbotForm").style.display = "block";
  document.querySelector(".open-button").style.display = "none";
}

// Close pop-up form
// Hide the chat window and show the open button
function closeForm() {
  document.getElementById("chatbotForm").style.display = "none";
  document.querySelector(".open-button").style.display = "block";
}

// close if Esc is pressed on the keyboard
// Allow closing the chat with the Escape key
document.addEventListener("keydown", event => {
  if (event.key === "Escape") {
    closeForm();
  }
});